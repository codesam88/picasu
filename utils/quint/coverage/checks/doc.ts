import { readFileSync, writeFileSync, mkdirSync, mkdtempSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { resolveBase } from "../lib/common.ts";

function load(name: string, specsDir: string): any {
  return JSON.parse(readFileSync(join(specsDir, name), "utf8"));
}

function render(specsDir: string): string {
  const goals = load("goals.json", specsDir);
  const assumptions = load("assumptions.json", specsDir);
  const scope = load("scope.json", specsDir);
  const requirements = load("requirements.json", specsDir);
  const events = load("events.json", specsDir);

  const lines: string[] = [];
  const add = (s: string = "") => lines.push(s);

  add("<!--Generated by utils/quint/coverage/bin/check.ts (docs) from");
  add(
    "utils/quint/pipeline/goals.json, utils/quint/pipeline/assumptions.json, utils/quint/pipeline/scope.json,",
  );
  add(
    "utils/quint/pipeline/requirements.json and utils/quint/pipeline/events.json. Edit those files, then",
  );
  add("regenerate: just quint docs-->");
  add();
  add(
    "# Eventual consistency: goals, assumptions, scope, requirements, implementation, events",
  );
  add();
  add("The catalogs answer different questions and depend on each other.");
  add("Assumptions state what the world gives the model. Goals are the");
  add(
    "outcomes humans commit to. Scope entries delimit what the proof covers.",
  );
  add("Requirements are concrete obligations derived from committed goals and");
  add("imposed on the implementation through gate tests. Implementation");
  add("records how each obligation was satisfied and which test gates it.");
  add("Events are the filesystem and API boundary inputs and recovery cases.");
  add(
    "Formal grounding lives in `utils/quint/pipeline/*.qnt`; the closed-world audit is",
  );
  add("`just spec-check`.");
  add();

  const modelSource = readFileSync(
    join(specsDir, "eventual-consistency.qnt"),
    "utf8",
  );
  const runCount = (modelSource.match(/^\s+run\s+\w+/gm) ?? []).length;
  const aspectSource = readFileSync(
    join(specsDir, "asset-aspects.qnt"),
    "utf8",
  );
  const aspectRunCount = (aspectSource.match(/^\s+run\s+\w+/gm) ?? []).length;
  const goalDecisions = new Map<string, number>();
  for (const g of goals.goals)
    goalDecisions.set(g.decision, (goalDecisions.get(g.decision) ?? 0) + 1);
  const openRequirements = requirements.requirements.filter(
    (r: any) => r.status === "open",
  );
  const verifiedRequirements = requirements.requirements.filter(
    (r: any) => r.status === "verified",
  );
  const assumptionStatuses = new Map<string, number>();
  for (const a of assumptions.assumptions)
    assumptionStatuses.set(
      a.status,
      (assumptionStatuses.get(a.status) ?? 0) + 1,
    );
  const eventStatuses = new Map<string, number>();
  for (const ev of events.events)
    eventStatuses.set(ev.status, (eventStatuses.get(ev.status) ?? 0) + 1);

  add("## Status");
  add();
  add(
    "Computed from the catalog statuses and `utils/quint/pipeline/eventual-consistency.qnt`;",
  );
  add("the modeled-scope line comes from `utils/quint/pipeline/scope.json`.");
  add();
  add(
    `- Proof: ${runCount} convergence runs + ${aspectRunCount} asset-aspect runs (${runCount + aspectRunCount} executed including imported runs; \`just quint-check\`); simulator traces are advisory.`,
  );
  add(
    `- Goals: ${goalDecisions.get("committed") ?? 0} committed, ${goalDecisions.get("queued") ?? 0} queued, ${goalDecisions.get("dropped") ?? 0} dropped.`,
  );
  add(
    `- Requirements: ${verifiedRequirements.length} verified, ${openRequirements.length} open${openRequirements.length ? ` (${openRequirements.map((r: any) => r.id).join(", ")})` : ""}.`,
  );
  add(
    `- Assumptions: ${[...assumptionStatuses].map(([status, count]) => `${count} ${status}`).join(", ")}.`,
  );
  add(
    `- Events: ${[...eventStatuses].map(([status, count]) => `${count} ${status}`).join(", ")}.`,
  );
  add(`- Current modeled scope: ${scope.modeled_scope}`);
  add();

  // Goals
  add("## Goals");
  add();
  add(goals.description);
  add();
  add("Source: `utils/quint/pipeline/goals.json`.");
  add();
  for (const g of goals.goals) {
    add(`### ${g.id}: ${g.title} (decision: ${g.decision})`);
    add();
    add(g.description);
    add();
    if (g.anchors.length > 0) {
      add("Anchors:");
      add();
      for (const a of g.anchors) add(`- ${a.kind}: \`${a.ref}\``);
      add();
    } else {
      add("Anchors: none — unanchored.");
      add();
    }
    if ((g.assumptions ?? []).length > 0) {
      add(`Holds under: ${g.assumptions.join(", ")}.`);
      add();
    }
    if (g.notes) {
      add(`Notes: ${g.notes}`);
      add();
    }
  }

  // Assumptions
  add("## Assumptions");
  add();
  add(assumptions.description);
  add();
  add("Source: `utils/quint/pipeline/assumptions.json`.");
  add();
  for (const a of assumptions.assumptions) {
    add(`### ${a.id}: ${a.title} (status: ${a.status})`);
    add();
    add(`Owner: ${a.owner}.`);
    add();
    if (a.status_note) {
      add(`Status note: ${a.status_note}`);
      add();
    }
  }

  // Scope
  add("## Scope");
  add();
  add(scope.description);
  add();
  add("Source: `utils/quint/pipeline/scope.json`.");
  add();
  for (const s of scope.scopes) {
    add(`### ${s.id}: ${s.title}`);
    add();
    add(`Bound: ${s.bound}`);
    add();
    add(`Why safe: ${s.why_safe}`);
    add();
    add(`Lifting: ${s.lifting}`);
    add();
    if (s.provisional) {
      add(
        "Provisional: the safety argument is weaker than the implementation guarantee.",
      );
      add();
    }
  }

  // Requirements
  add("## Requirements");
  add();
  add(requirements.description);
  add();
  add("Requirements are derived from committed goals and imposed on the");
  add(
    "implementation through gate tests. Source: `utils/quint/pipeline/requirements.json`.",
  );
  add();
  for (const r of requirements.requirements) {
    add(`### ${r.id}: ${r.title} (status: ${r.status})`);
    add();
    add(r.statement);
    add();
    add(`Derived from: ${r.derived_from.join(", ")}. Owner: ${r.owner}.`);
    add();
    add(`Gate: ${r.gate}`);
    add();
  }

  // Implementation
  add("## Implementation");
  add();
  add("How each requirement was satisfied, its gate tests, and known limits.");
  add(
    "Source: `utils/quint/pipeline/requirements.json` (`implementation`, `tests`,",
  );
  add("`limits`). Use `git log --grep REQ-N` to review one requirement.");
  add();
  for (const r of requirements.requirements) {
    add(`### ${r.id}: ${r.title} (status: ${r.status})`);
    add();
    add(`Implementation: ${r.implementation}`);
    add();
    if (r.tests.length > 0) {
      add("Tests:");
      for (const t of r.tests) add(`- \`${t}\``);
    } else {
      add("Tests: none yet.");
    }
    add();
    if (r.limits) {
      add(`Limits: ${r.limits}`);
      add();
    }
  }

  // Events
  add("## Events");
  add();
  add(events.description);
  add();
  add("Source: `utils/quint/pipeline/events.json`.");
  add();
  for (const ev of events.events) {
    add(`### ${ev.name} (${ev.status}, actor: ${ev.actor})`);
    add();
    add(ev.description);
    add();
    add(`Target: ${ev.target}. Code anchor: \`${ev.code_ref}\`.`);
    add();
    if (ev.preconditions.length > 0) {
      add(`Preconditions: ${ev.preconditions.join("; ")}.`);
      add();
    }
    if (ev.affected_state.length > 0) {
      add(`Touches: ${ev.affected_state.join(", ")}.`);
      add();
    }
    add("Effects (settled state assuming quiescence after the event):");
    add();
    for (const eff of ev.effects) add(`- ${eff}`);
    add();
    if (ev.faults.length > 0) {
      add("Faults:");
      add();
      for (const f of ev.faults) {
        add(`- ${f.fault} (${f.status}): ${f.consequence}`);
      }
      add();
    }
    if (ev.notes) {
      add(`Notes: ${ev.notes}`);
      add();
    }
  }

  return lines.join("\n") + "\n";
}

export function docs(args: string[]): number {
  const base = resolveBase(args[0] ?? ".", "events.json");
  const outFile = args[1];
  if (!outFile) {
    console.error("docs: missing required output file argument");
    return 2;
  }
  const outPath = resolve(outFile);
  const md = render(base);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, md, "utf8");
  console.log(`gen-eventual-consistency-doc: wrote ${outPath}`);
  return 0;
}

export function docCheck(args: string[]): number {
  const base = resolveBase(args[0] ?? ".", "events.json");
  const committedFile = args[1];
  if (!committedFile) {
    console.error("doc-check: missing required committed-file argument");
    return 2;
  }
  const target = resolve(committedFile);
  const tmpdir = mkdtemp();
  const generatedPath = join(tmpdir, "regenerated.md");
  const md = render(base);
  writeFileSync(generatedPath, md, "utf8");

  let existing = "";
  try {
    existing = readFileSync(target, "utf8");
  } catch {
    existing = "";
  }
  const generated = readFileSync(generatedPath, "utf8");
  if (existing !== generated) {
    console.error(diffSimple(existing, generated));
    console.error("");
    console.error(
      "docs/eventual-consistency.md is out of date with the generator.",
    );
    console.error("Run 'just quint docs' and commit the result.");
    return 1;
  }
  console.log("docs/eventual-consistency.md matches the generated output");
  return 0;
}

function mkdtemp(): string {
  return mkdtempSync(join(tmpdir(), "quint-doc-"));
}

function diffSimple(a: string, b: string): string {
  // Use system diff via child_process for readable output
  const d = mkdtempSync(join(tmpdir(), "quint-diff-"));
  const pa = join(d, "a.md");
  const pb = join(d, "b.md");
  writeFileSync(pa, a);
  writeFileSync(pb, b);
  const r = spawnSync("diff", ["-u", pa, pb], { encoding: "utf8" });
  return r.stdout ?? "";
}
